// A real backend with a fresh database per invocation. No existing server/database reuse.
import { spawn } from 'node:child_process'
import { mkdtemp, rm } from 'node:fs/promises'
import { createServer as createNetServer } from 'node:net'
import { tmpdir } from 'node:os'
import { join, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build, preview } from 'vite'

const frontend = fileURLToPath(new URL('..', import.meta.url))
const backendRoot = resolve(frontend, '..', 'backend')
const port = readPort('E2E_PORT', 4179)
const apiPort = readPort('E2E_API_PORT', 18089)
if (port === apiPort) throw new Error('E2E ports must differ')
await checkPort(port)
await checkPort(apiPort)
const scratch = await mkdtemp(join(tmpdir(), 'dengovod-e2e-'))
const database = join(scratch, 'test.sqlite')
const executable = join(scratch, process.platform === 'win32' ? 'backend.exe' : 'backend')
let backend
let vite
let stopping = false

function readPort(name, fallback) {
  const value = Number(process.env[name] ?? fallback)
  if (!Number.isInteger(value) || value < 1024 || value > 65535) throw new Error(`Invalid ${name}`)
  return value
}

async function checkPort(value) {
  await new Promise((done, fail) => {
    const server = createNetServer()
    server.once('error', fail)
    server.listen(value, '127.0.0.1', () => server.close(done))
  })
}

async function stop(code = 0) {
  if (stopping) return
  stopping = true
  await vite?.close()
  if (backend && backend.exitCode === null) {
    await new Promise((done) => {
      backend.once('exit', done)
      backend.kill()
    })
  }
  // scratch is generated by mkdtemp, never taken from environment/user settings.
  if (resolve(scratch).startsWith(resolve(tmpdir()) + sep) && scratch.includes('dengovod-e2e-')) {
    await rm(scratch, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 })
  }
  process.exit(code)
}

process.on('SIGINT', () => void stop())
process.on('SIGTERM', () => void stop())

try {
  console.log(`[e2e] isolated SQLite: ${database}; API: 127.0.0.1:${apiPort}`)
  await new Promise((done, fail) => {
    const build = spawn('go', ['build', '-o', executable, './cmd/server'], { cwd: backendRoot, stdio: 'inherit', windowsHide: true })
    build.once('error', fail)
    build.once('exit', (code) => code === 0 ? done() : fail(new Error(`Go build exited ${code}`)))
  })
  backend = spawn(executable, [], {
    cwd: scratch,
    env: { ...process.env, DATABASE_PATH: database, HTTP_ADDR: `127.0.0.1:${apiPort}` },
    stdio: 'inherit',
    windowsHide: true,
  })
  backend.once('error', (error) => { console.error(error); void stop(1) })
  backend.once('exit', (code) => { if (!stopping) { console.error(`[e2e] backend exited ${code}`); void stop(1) } })
  let ready = false
  for (let attempt = 0; attempt < 100; attempt++) {
    try {
      const response = await fetch(`http://127.0.0.1:${apiPort}/api/v1/settings`, { signal: AbortSignal.timeout(1000) })
      if (response.status === 401) { ready = true; break }
    } catch { /* startup */ }
    await new Promise((done) => setTimeout(done, 100))
  }
  if (!ready) throw new Error('Isolated backend did not become ready')
  const webOutput = join(scratch, 'web')
  await build({ root: frontend, build: { outDir: webOutput, emptyOutDir: true } })
  vite = await preview({
    root: frontend,
    build: { outDir: webOutput },
    preview: {
      host: '127.0.0.1', port, strictPort: true,
      proxy: { '/api': `http://127.0.0.1:${apiPort}` },
    },
    plugins: [{
      name: 'isolated-e2e-lifecycle',
      configurePreviewServer(server) {
        server.middlewares.use((req, res, next) => {
          if (req.url === '/__e2e__/ready') {
            res.end('isolated-e2e-ready')
          } else if (req.url === '/__e2e__/shutdown' && req.method === 'POST' && process.env.E2E_RUN_TOKEN && req.headers['x-e2e-run-token'] === process.env.E2E_RUN_TOKEN) {
            res.end('stopping')
            setTimeout(() => void stop(), 50)
          } else next()
        })
      },
    }],
  })
  console.log(`[e2e] frontend ready at http://127.0.0.1:${port}`)
} catch (error) {
  console.error(error)
  await stop(1)
}
