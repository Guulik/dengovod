import { expect, test } from '@playwright/test'
import { assertNoHorizontalOverflow, dayDetail, loginUI } from './helpers'
import { captureDayEditor, dayMetric, openDayCost, rublesPattern, saveDayCost, seedDayCosts, selectDay, shiftDate, verifyFinancials } from './dv8-helpers'

test.describe('DV8: стоимость выбранного дня на настоящем API', () => {
  test.setTimeout(45_000)

  test('прошлый день: сохранение 1000, ноль и повтор 700 обновляют остаток без изменения соседних дней', async ({ page, request }, testInfo) => {
    const profile = await seedDayCosts(request)
    await verifyFinancials(request, profile, profile.yesterday, { balance: 17200, cost: 1400, evening: 17200, life: 15800 })
    await loginUI(page, profile.login)
    await selectDay(page, profile.yesterday)
    const selectedHeading = await dayDetail(page).getByRole('heading', { level: 2 }).textContent()
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(1400))
    await saveDayCost(page, profile.yesterday, '1000', '1400', true)
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(1000))
    await expect(dayMetric(page, 'Баланс вечером')).toContainText(rublesPattern(17600))
    await expect(page.getByRole('button', { name: /Текущий баланс/ })).toContainText(rublesPattern(17600))
    await expect(page.getByRole('article').filter({ hasText: 'Деньги на жизнь' })).toContainText(rublesPattern(16200))
    await expect(dayDetail(page).getByRole('heading', { level: 2 })).toHaveText(selectedHeading!)
    await verifyFinancials(request, profile, profile.yesterday, { balance: 17600, cost: 1000, evening: 17600, life: 16200 })
    await assertNoHorizontalOverflow(page)
    if (testInfo.project.name === 'mobile-390') await captureDayEditor(page, profile.yesterday, 390, '1000')

    // A later overlapping period outranks the first single-day rule. The next
    // day edit must append a fresh POST, rather than update that old rule in place.
    const laterResponse = await request.post('/api/v1/day-cost-overrides', {
      headers: profile.headers,
      data: { date_from: profile.yesterday, date_to: profile.tomorrow, daily_amount: { amount: 200000, currency: 'RUB' }, comment: 'DV8: более поздний перекрывающийся период' },
    })
    expect(laterResponse.ok()).toBeTruthy()
    const laterPeriod = await laterResponse.json()
    await page.reload()
    await selectDay(page, profile.yesterday)
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(2000))
    await verifyFinancials(request, profile, profile.yesterday, { balance: 16600, cost: 2000, evening: 16600, life: 14600 })

    if (testInfo.project.name === 'mobile-390') await page.setViewportSize({ width: 320, height: 844 })
    await saveDayCost(page, profile.yesterday, '0', '2000')
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(0))
    await expect(page.getByRole('button', { name: /Текущий баланс/ })).toContainText(rublesPattern(18600))
    await verifyFinancials(request, profile, profile.yesterday, { balance: 18600, cost: 0, evening: 18600, life: 16600 })
    await saveDayCost(page, profile.yesterday, '700', '0')
    await expect(dayMetric(page, 'Баланс вечером')).toContainText(rublesPattern(17900))
    await expect(page.getByRole('button', { name: /Текущий баланс/ })).toContainText(rublesPattern(17900))
    await verifyFinancials(request, profile, profile.yesterday, { balance: 17900, cost: 700, evening: 17900, life: 15900 })
    await assertNoHorizontalOverflow(page)
    if (testInfo.project.name === 'mobile-390') await captureDayEditor(page, profile.yesterday, 320, '700')

    const overrideResponse = await request.get('/api/v1/day-cost-overrides', { headers: profile.headers })
    const rules = (await overrideResponse.json()).overrides
    const broad = rules.find((item: { id: string }) => item.id === profile.broadOverrideId)
    expect(broad).toMatchObject({ date_from: profile.start, date_to: profile.tomorrow, daily_amount: { amount: 140000, currency: 'RUB' } })
    expect(rules.find((item: { id: string }) => item.id === laterPeriod.id)).toEqual(laterPeriod)
    await page.reload()
    await selectDay(page, profile.yesterday)
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(700))
    await expect(dayMetric(page, 'Баланс вечером')).toContainText(rublesPattern(17900))
    await expect(page.getByRole('button', { name: /Текущий баланс/ })).toContainText(rublesPattern(17900))
    await verifyFinancials(request, profile, profile.start, { balance: 17900, cost: 1400, evening: 18600, life: 15900 })
    await verifyFinancials(request, profile, profile.today, { balance: 17900, cost: 2000, evening: 15900, life: 15900 })
  })

  test('будущий день и другой override-период: изменение не списывает деньги сейчас', async ({ page, request }, testInfo) => {
    const profile = await seedDayCosts(request)
    const otherFrom = shiftDate(profile.today, 10)
    const otherTo = shiftDate(profile.today, 12)
    const otherResponse = await request.post('/api/v1/day-cost-overrides', {
      headers: profile.headers,
      data: { date_from: otherFrom, date_to: otherTo, daily_amount: { amount: 27500, currency: 'RUB' }, comment: 'DV8: другой период, сохранить' },
    })
    expect(otherResponse.ok()).toBeTruthy()
    const other = await otherResponse.json()
    await loginUI(page, profile.login)
    await selectDay(page, profile.tomorrow)
    await saveDayCost(page, profile.tomorrow, '0', '1400')
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(0))
    await expect(dayMetric(page, 'Баланс вечером')).toContainText(rublesPattern(15800))
    await expect(page.getByRole('button', { name: /Текущий баланс/ })).toContainText(rublesPattern(17200))
    await verifyFinancials(request, profile, profile.tomorrow, { balance: 17200, cost: 0, evening: 15800, life: 15800 })
    if (testInfo.project.name === 'mobile-390') await page.setViewportSize({ width: 320, height: 844 })
    await saveDayCost(page, profile.tomorrow, '900', '0')
    await verifyFinancials(request, profile, profile.tomorrow, { balance: 17200, cost: 900, evening: 14900, life: 15800 })
    await page.reload()
    await selectDay(page, profile.tomorrow)
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(900))
    await expect(dayMetric(page, 'Баланс вечером')).toContainText(rublesPattern(14900))
    await expect(page.getByRole('button', { name: /Текущий баланс/ })).toContainText(rublesPattern(17200))
    const overrides = await request.get('/api/v1/day-cost-overrides', { headers: profile.headers })
    expect((await overrides.json()).overrides.find((item: { id: string }) => item.id === other.id)).toEqual(other)
    await assertNoHorizontalOverflow(page)
  })

  test('без якоря: ошибка соединения сохраняет ввод, повтор и последующий ноль сохраняются без события', async ({ page, request }, testInfo) => {
    const profile = await seedDayCosts(request, false)
    await loginUI(page, profile.login)
    await selectDay(page, profile.yesterday)
    const controls = await openDayCost(page, '0')
    await controls.amount.fill('1000')
    await page.route('**/api/v1/day-cost-overrides**', (route) => {
      if (['POST', 'PUT'].includes(route.request().method())) return route.abort('connectionrefused')
      return route.continue()
    })
    await controls.save.click()
    await expect(controls.editor.getByRole('alert')).toBeVisible()
    await expect(controls.amount).toHaveValue('1000')
    const unchanged = await request.get('/api/v1/day-cost-overrides', { headers: profile.headers })
    expect((await unchanged.json()).overrides).toEqual([])
    await page.unroute('**/api/v1/day-cost-overrides**')
    const saved = page.waitForResponse((response) => response.url().includes('/api/v1/day-cost-overrides') && ['POST', 'PUT'].includes(response.request().method()))
    await controls.save.click()
    expect((await saved).ok()).toBeTruthy()
    await expect(controls.editor).toBeHidden()
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(1000))
    if (testInfo.project.name === 'mobile-390') await page.setViewportSize({ width: 320, height: 844 })
    await saveDayCost(page, profile.yesterday, '0', '1000')
    await page.reload()
    await selectDay(page, profile.yesterday)
    await expect(dayMetric(page, 'Стоимость дня')).toContainText(rublesPattern(0))
    await expect(dayMetric(page, 'Баланс вечером')).toContainText('—')
    const calendarResponse = await request.get(`/api/v1/calendar?from=${profile.yesterday}&to=${profile.yesterday}`, { headers: profile.headers })
    const data = await calendarResponse.json()
    expect(data.summary).toBeNull()
    expect(data.days[0].expected_balance).toBeNull()
    expect(data.days[0].day_cost.amount).toBe(0)
    expect(data.days[0].events).toEqual([])
    const overrides = await request.get('/api/v1/day-cost-overrides', { headers: profile.headers })
    expect((await overrides.json()).overrides).toContainEqual(expect.objectContaining({ date_from: profile.yesterday, date_to: profile.yesterday, daily_amount: { amount: 0, currency: 'RUB' } }))
    await assertNoHorizontalOverflow(page)
  })
})
