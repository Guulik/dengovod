import { expect, test, type Page } from '@playwright/test'
import { assertNoHorizontalOverflow, calendar, dayCell, dayDetail, loginUI, moscowToday, seedProfile, uniqueLogin } from './helpers'

async function openSalary(page: Page) {
  await expect(calendar(page)).toBeVisible()
  await dayCell(page, moscowToday()).click()
  await dayDetail(page).getByRole('button', { name: 'Добавить', exact: true }).click()
  const modal = page.getByRole('dialog', { name: 'Новое событие' })
  await modal.getByText('Доход', { exact: true }).click()
  await modal.getByRole('combobox', { name: 'Категория', exact: true }).selectOption({ label: 'Зарплата' })
  const calculator = modal.getByRole('group', { name: 'Калькулятор зарплаты', exact: true })
  await expect(calculator).toBeVisible()
  return { modal, calculator }
}

test('зарплата числом дней: 100000 × 15 / 30, явное применение, ручная сумма, дата выплаты', async ({ page, request }) => {
  const profile = await seedProfile(request, 10000)
  await loginUI(page, profile.login)
  const { modal, calculator } = await openSalary(page)
  const payout = moscowToday()
  const comment = `Зарплата числом ${uniqueLogin()}`
  await modal.getByLabel('Сумма, ₽', { exact: true }).fill('123')
  await calculator.getByLabel('Оклад за полный месяц, ₽').fill('100000')
  await calculator.getByLabel('Расчётный месяц').fill('2026-04')
  await calculator.getByLabel('Отработано календарных дней').fill('15')
  await expect(calculator).toContainText(/Итого: 50\s*000/)
  await expect(calculator).toContainText('15 из 30')
  await expect(calculator).toContainText('без производственного календаря')
  await expect(calculator).toContainText('формула не сохраняется')
  await expect(modal.getByLabel('Сумма, ₽', { exact: true })).toHaveValue('123')
  await calculator.getByRole('button', { name: 'Применить к сумме' }).click()
  await expect(modal.getByLabel('Сумма, ₽', { exact: true })).toHaveValue('50000')
  await expect(modal.getByLabel('Дата начала', { exact: true })).toHaveValue(payout)
  await modal.getByLabel('Сумма, ₽', { exact: true }).fill('50001,23')
  await modal.getByLabel('Комментарий', { exact: true }).fill(comment)
  await assertNoHorizontalOverflow(page)
  const saved = page.waitForResponse((response) => response.url().endsWith('/events') && response.request().method() === 'POST')
  await modal.getByRole('button', { name: 'Сохранить', exact: true }).click()
  const response = await saved
  expect(response.ok()).toBeTruthy()
  const data = await response.json()
  expect(data.amount.amount).toBe(5_000_123)
  expect(data.recurrence.start_date).toBe(payout)
  await expect(modal).toBeHidden()
  await page.reload()
  await dayCell(page, payout).click()
  await dayDetail(page).getByRole('article').filter({ hasText: comment }).getByRole('button', { name: 'Изменить серию' }).click()
  const editor = page.getByRole('dialog', { name: 'Редактировать событие' })
  await expect(editor.getByLabel('Сумма, ₽', { exact: true })).toHaveValue('50001,23')
  await expect(editor.getByLabel('Дата начала', { exact: true })).toHaveValue(payout)
})

test('зарплата уникальными датами високосного февраля сохраняет сумму и дату выплаты', async ({ page, request }) => {
  const profile = await seedProfile(request, 10000)
  await loginUI(page, profile.login)
  const { modal, calculator } = await openSalary(page)
  await calculator.getByLabel('Оклад за полный месяц, ₽').fill('100000')
  await calculator.getByLabel('Расчётный месяц').fill('2024-02')
  await calculator.getByLabel('Как указать отработанные дни').selectOption('dates')
  const dates = calculator.getByRole('group', { name: 'Отработанные даты' })
  await expect(dates.getByRole('checkbox')).toHaveCount(29)
  await dates.getByText('1', { exact: true }).click()
  await dates.getByText('29', { exact: true }).click()
  await expect(calculator).toContainText('2 из 29')
  await expect(calculator).toContainText(/6\s*896,55/)
  await dates.getByText('29', { exact: true }).click()
  await expect(calculator).toContainText('1 из 29')
  await dates.getByText('29', { exact: true }).click()
  await expect(calculator).toContainText('2 из 29')
  await calculator.getByRole('button', { name: 'Применить к сумме' }).click()
  await expect(modal.getByLabel('Сумма, ₽', { exact: true })).toHaveValue('6896,55')
  await expect(modal.getByLabel('Дата начала', { exact: true })).toHaveValue(moscowToday())
  await modal.getByLabel('Комментарий', { exact: true }).fill(`Зарплата датами ${uniqueLogin()}`)
  await assertNoHorizontalOverflow(page)
  const saved = page.waitForResponse((response) => response.url().endsWith('/events') && response.request().method() === 'POST')
  await modal.getByRole('button', { name: 'Сохранить', exact: true }).click()
  const response = await saved
  expect(response.ok()).toBeTruthy()
  const data = await response.json()
  expect(data.amount.amount).toBe(689_655)
  expect(data.recurrence.start_date).toBe(moscowToday())
  await expect(modal).toBeHidden()
})

test('калькулятор: 28/31 день, half-up, неверный ввод, ноль и сброс режимов', async ({ page, request }) => {
  const profile = await seedProfile(request, 10000)
  await loginUI(page, profile.login)
  const { modal, calculator } = await openSalary(page)
  const apply = calculator.getByRole('button', { name: 'Применить к сумме' })
  await calculator.getByLabel('Оклад за полный месяц, ₽').fill('0,01')
  await calculator.getByLabel('Расчётный месяц').fill('2025-02')
  await calculator.getByLabel('Отработано календарных дней').fill('14')
  await expect(calculator).toContainText('14 из 28')
  await expect(calculator).toContainText('Итого: 0,01')
  await apply.click()
  await expect(modal.getByLabel('Сумма, ₽', { exact: true })).toHaveValue('0,01')
  await calculator.getByLabel('Расчётный месяц').fill('2026-01')
  await calculator.getByLabel('Отработано календарных дней').fill('31')
  await expect(calculator).toContainText('31 из 31')
  for (const invalid of ['32', '-1', '1.5']) {
    await calculator.getByLabel('Отработано календарных дней').fill(invalid)
    await expect(apply).toBeDisabled()
  }
  await calculator.getByLabel('Отработано календарных дней').fill('1')
  for (const invalid of ['-100', 'abc', '100.001', '9007199254740992']) {
    await calculator.getByLabel('Оклад за полный месяц, ₽').fill(invalid)
    await expect(apply).toBeDisabled()
  }
  await calculator.getByLabel('Оклад за полный месяц, ₽').fill('100000')
  await calculator.getByLabel('Отработано календарных дней').fill('15')
  await calculator.getByLabel('Как указать отработанные дни').selectOption('dates')
  await expect(calculator.getByRole('checkbox', { checked: true })).toHaveCount(0)
  await expect(calculator).toContainText('0 из 31')
  await calculator.getByRole('group', { name: 'Отработанные даты' }).getByText('1', { exact: true }).click()
  await calculator.getByLabel('Как указать отработанные дни').selectOption('count')
  await expect(calculator.getByLabel('Отработано календарных дней')).toHaveValue('0')
  await apply.click()
  await expect(modal.getByLabel('Сумма, ₽')).toHaveValue('0')
  await modal.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(modal).toBeVisible()
  await expect(modal).toContainText(/положительную сумму|больше нуля/i)
  await assertNoHorizontalOverflow(page)
})
